from langgraph.graph.message import add_messages
from langchain_core.messages import AnyMessage
from pydantic import BaseModel, Field
from typing import Annotated, Literal, Optional, Any
from operator import add


class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(default_factory=list, description="List of messages associated with the agent")
    user_question: str = Field(default="", description="The question asked by the user")
    curated_question: str = Field(default="", description="Cleaned-up version of the user's question")
    prompt_context: str = Field(default="", description="Full prompt (question + DB schema) for the SQL generator")
    generated_sql_query: str = Field(default="", description="The SQL query generated by the agent")
    is_safe_sql_response: str = Field(default="", description="Judge verdict on the SQL: 'Yes' or 'No'")
    comments: str = Field(default="", description="Judge/guardrail explanation of the safety verdict")
    sql_query_execution_result: Any = Field(default=None, description="Raw result of the executed SQL query")
    execution_error: str = Field(default="", description="Database error from the last execution attempt, if any")
    retry_count: int = Field(default=0, description="Number of failed execution attempts so far")
    final_answer: str = Field(default="", description="The final answer returned to the user")


class JudgeSchema(BaseModel):
    is_safe: Literal["Yes", "No"] = Field(description="Whether the SQL query is strictly read-only")
    risk_category: Literal["READ_ONLY", "DML_MUTATION", "DDL_MUTATION", "CODE_EXECUTION", "INJECTION_RISK"] = Field(
        description="Category of risk found in the query"
    )
    explanation: str = Field(description="Short rationale for the verdict")
    
class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="List of messages associated with the agent",
    )
    
class DecideSchema(BaseModel):
    answer: Literal["sql_analyst", "etl_analyst"]
    output_format: Optional[Literal["csv", "json", "parquet", "xlsx"]] = None

class DataAgentSchema(BaseModel):
    messages: Annotated[list[AnyMessage], add_messages]
    main_response: Optional[str] = None
    output_format: Optional[str] = None
    output_name: Optional[str] = None
    result_records: Optional[list[dict]] = None   # rows kept as plain dicts so Pydantic is happy
    final_answer: Optional[str] = None
    output_file: Optional[str] = None
    error: Optional[str] = None